"""
production_calendar.py
───────────────────────
Официальный производственный календарь РФ (5-дневная неделя) — количество
рабочих дней в месяце с учётом праздников и переносов. Источник: КонсультантПлюс.

ВАЖНО: наивный подсчёт "будних дней" (пн-пт по календарю) даёт неверный
результат в месяцах с праздниками (январь, февраль, май, июнь, ноябрь) —
разница может достигать 5-7 дней. Используйте эти данные, а не
calendar.weekday()-подсчёт, для любого графика 5/2, где важна точность.

Как обновлять на новый год: как только Постановление Правительства РФ
о переносе выходных на следующий год опубликовано (обычно в сентябре
текущего года), добавьте новую запись в PRODUCTION_WORKDAYS ниже.
Источник: https://www.consultant.ru/law/ref/calendar/proizvodstvennye/<год>/
"""
import calendar

# {(год, месяц): рабочих_дней} — только годы с ПОДТВЕРЖДЁННЫМ официальным
# календарём (проверено поиском на consultant.ru). Для остальных лет/месяцев
# используется приближение (см. _naive_workdays ниже) — точность ниже,
# особенно в праздничных месяцах (январь, февраль, май, июнь, ноябрь).
#
# Проверено на дату сборки этого файла: 2026 (весь год), 2027 (весь год).
# Год 2028+ и 2025 и ранее — НЕ подтверждены, при работе с ними сверьтесь
# с https://www.consultant.ru/law/ref/calendar/proizvodstvennye/
PRODUCTION_WORKDAYS = {
    (2026, 1): 15, (2026, 2): 19, (2026, 3): 21, (2026, 4): 22,
    (2026, 5): 19, (2026, 6): 21, (2026, 7): 23, (2026, 8): 21,
    (2026, 9): 22, (2026, 10): 22, (2026, 11): 20, (2026, 12): 22,

    (2027, 1): 15, (2027, 2): 19, (2027, 3): 22, (2027, 4): 22,
    (2027, 5): 19, (2027, 6): 21, (2027, 7): 22, (2027, 8): 22,
    (2027, 9): 22, (2027, 10): 21, (2027, 11): 20, (2027, 12): 22,
}


def _naive_workdays(yr: int, mn: int) -> int:
    """Запасной вариант для года без данных в таблице — считает пн-пт
    по календарю БЕЗ учёта праздников. Занижает точность на 5-7 дней
    в праздничных месяцах — использовать только как временную оценку."""
    days = calendar.monthrange(yr, mn)[1]
    return sum(1 for d in range(1, days + 1) if calendar.weekday(yr, mn, d) < 5)


def workdays_5x2(yr: int, mn: int) -> tuple[int, bool]:
    """
    Рабочих дней в месяце при графике 5/2, с учётом праздников РФ.
    Возвращает (количество_дней, из_официального_календаря).
    Второе значение False означает, что использован приближённый расчёт
    (год ещё не в PRODUCTION_WORKDAYS) — стоит проверить вручную ближе к делу.
    """
    key = (yr, mn)
    if key in PRODUCTION_WORKDAYS:
        return PRODUCTION_WORKDAYS[key], True
    return _naive_workdays(yr, mn), False


def workdays_5x2_range(yr: int, mn: int, day_start: int, day_end: int) -> int:
    """
    Рабочих дней в ЧАСТИ месяца (частичный первый/последний месяц контракта).
    Праздники внутри диапазона учитываются, только если известна конкретная
    дата праздника для этого года — для простоты здесь считаем по будним
    дням (пн-пт) без вычета праздников: на практике частичные месяцы почти
    всегда приходятся на края периода (сентябрь и т.п.), где праздников нет.
    Если частичный месяц захватывает известный праздничный период (январь,
    февраль, май, июнь, ноябрь) — посчитайте вручную и передайте override.
    """
    return sum(1 for d in range(day_start, day_end + 1) if calendar.weekday(yr, mn, d) < 5)
